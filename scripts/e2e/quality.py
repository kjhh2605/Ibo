METRICS=('neckColorDeltaE95','shoulderColorDeltaE95','neckOffsetRatio95','shoulderOffsetRatio95')


def image_url(raw):
    with Image.open(io.BytesIO(raw)) as image:
        require(image.format in {'PNG','JPEG'},'poc_image_format')
        require(image.width<=2048 and image.height<=2048,'poc_input_dimensions')
        mime='image/png' if image.format=='PNG' else 'image/jpeg'
    require(len(raw)<=4*1048576,'poc_input_too_large')
    return 'data:'+mime+';base64,'+base64.b64encode(raw).decode()


def provider_image(value):
    images=[]
    for output in value.get('output',[]):
        if output.get('type')=='image_generation_call' and isinstance(output.get('result'),str):images.append(output['result'])
        for item in output.get('content',[]):
            if item.get('type')=='image' and isinstance(item.get('data'),str):images.append(item['data'])
    require(len(images)==1,'poc_provider_image_missing_or_ambiguous')
    raw=base64.b64decode(images[0],validate=True)
    require(len(raw)<=32*1048576,'poc_provider_image_too_large')
    with Image.open(io.BytesIO(raw)) as image:image.verify()
    return raw


def thresholds_from_review(rows, review):
    accepted=[]
    for row in rows:
        label=review.get('outputs',{}).get(row['id'])
        require(label and label.get('providerSha256')==row.get('providerSha256'),'calibration_review_missing_or_stale')
        if label.get('acceptableComposition') is True:
            metrics=row.get('evaluation',{}).get('metrics')
            require(metrics and all(type(metrics.get(k)) in (int,float) and math.isfinite(metrics[k]) and metrics[k]>=0 for k in METRICS),'accepted_output_has_unavailable_metrics')
            accepted.append(metrics)
    require(accepted,'calibration_has_no_acceptable_outputs')
    value={'maxBoundaryColorDeltaE':max(m[k] for m in accepted for k in METRICS[:2]),'maxBoundaryOffsetRatio':max(m[k] for m in accepted for k in METRICS[2:])}
    value['version']='s11-'+hashlib.sha256(json.dumps(value,sort_keys=True).encode()).hexdigest()[:16]
    return value


def decision(metrics, thresholds):
    if thresholds is None:return 'not_calibrated'
    if not metrics or any(type(metrics.get(k)) not in (int,float) or not math.isfinite(metrics[k]) or metrics[k]<0 for k in METRICS):return 'metrics_unavailable'
    return 'composited' if all(metrics[k]<=thresholds['maxBoundaryColorDeltaE'] for k in METRICS[:2]) and all(metrics[k]<=thresholds['maxBoundaryOffsetRatio'] for k in METRICS[2:]) else 'threshold_exceeded'


def poc(run,args):
    require(args.plan==16 and args.mode=='live','poc_requires_live_16_plan')
    human_head_inputs()
    if not os.environ.get('MODEL_API_KEY') or not os.environ.get('RELAY_HMAC_SECRET'):
        raise Blocked('M1 local MODEL_API_KEY and RELAY_HMAC_SECRET required; never copy them into reports')
    plan=load(FIX/'quality/cases.json');review=load(FIX/'review/head.json')
    cases={c['id']:c for c in review['cases']}
    require(len(plan['calibration'])==2 and len(plan['heldOut'])==2 and not set(plan['calibration'])&set(plan['heldOut']),'quality_split_not_frozen')
    garments=['images/derived/shop-2-candidate-1.png','images/wardrobe/jeans-cutout.png','images/wardrobe/shoes-cutout.png']
    approved_assets(garments)
    install_driver()
    cache=Path.home()/'.cache/street-fitting/poc'/run.id
    cache.mkdir(parents=True,exist_ok=False)
    rows=[];base_source=run.id
    if args.resume:
        source=run_path(args.resume);previous=load(source/'poc-progress.json')
        require(previous['planSha256']==hashlib.sha256((FIX/'quality/cases.json').read_bytes()).hexdigest(),'poc_plan_changed_on_resume')
        rows=previous['calls'];base_source=previous.get('baseSource',args.resume)
        require(len(rows) in {12,16},'resume_requires_complete_base_or_complete_plan')
        require(all(row.get('status')=='passed' for row in rows),'cannot_hide_failed_poc_calls_by_resuming')
    masked={};staged=[]
    secret=base64.b64decode(os.environ['RELAY_HMAC_SECRET'],validate=True)
    sub=hmac.new(secret,b'safety:v1:s11-synthetic-poc',hashlib.sha256).hexdigest()
    def progress():
        # Count attempted provider calls even when calibration pauses for review.
        run.data['providerCalls']=len(rows)
        run.data['newProviderCalls']=len([row for row in rows if row.get('localCacheRun',run.id)==run.id])
        run.save('poc-progress.json',{'baseSource':base_source,'planSha256':hashlib.sha256((FIX/'quality/cases.json').read_bytes()).hexdigest(),'calls':rows,'providerCalls':len(rows),'source':'separate approved-synthetic Muse Image experiment; not app live E2E'})
    def inputs(case_id, mode):
        key=(case_id,mode)
        if key not in masked:
            case=cases[case_id];source=stage_file(FIX/case['image']);gt=stage_file(FIX/case['groundTruthMask']);staged.extend([source,gt])
            target=BASE+'/'+hashlib.sha256((run.id+case_id+mode).encode()).hexdigest()+'.png';staged.append(target)
            proof=invoke({'operation':'mask','source':source,'groundTruth':gt,'mode':mode,'maskedOutput':target})
            require(proof['exposedHeadPixels']==0,'poc_mask_exposes_head')
            masked[key]=(read_private(target),source,proof)
        return masked[key]
    def evaluate(case_id,mode,raw,thresholds=None):
        _,source,mask_proof=inputs(case_id,mode)
        provider=stage_bytes(raw,'.png');staged.append(provider)
        return invoke({'operation':'measure','source':source,'provider':provider,'cropOffset':mask_proof['cropOffset'],'thresholds':thresholds})
    def call(client,case_id,mode,reasoning,kind,thresholds=None):
        ordinal=len(rows)+1;row={'id':f'call-{ordinal:02}','case':case_id,'maskMode':mode,'reasoning':reasoning,'kind':kind,'status':'attempted'}
        raw,_,proof=inputs(case_id,mode)
        content=[{'type':'input_text','text':'Create one realistic virtual try-on. The first image is the approved face-and-hair-removed adult body. Dress that body in the next garment images; preserve pose and body geometry. Do not add a face or hair. Return one image.'},{'type':'input_image','image_url':image_url(raw)}]
        chosen=garments[:1] if kind=='top-only' else garments
        content.extend({'type':'input_image','image_url':image_url((FIX/name).read_bytes())} for name in chosen)
        payload={'model':'muse-image-1.0','store':False,'safety_identifier':sub,'input':[{'role':'user','content':content}],
                 'tools':[{'type':'image_generation','output_format':'png','reasoning_strength':reasoning,'enable_image_search':False,'enable_web_search':False,'enable_shell':False}]}
        rows.append(row);progress();start=time.monotonic()
        try:
            response=client.post('https://api.meta.ai/v1/responses',json=payload,headers={'Authorization':'Bearer '+os.environ['MODEL_API_KEY']})
            row['statusCode']=response.status_code;row['elapsedMs']=round((time.monotonic()-start)*1000)
            require(response.status_code==200,'poc_provider_failed')
            provider=provider_image(response.json());sha=hashlib.sha256(provider).hexdigest()
            (cache/(sha+'.png')).write_bytes(provider)
            row.update(providerSha256=sha,providerBytes=len(provider),localCacheRun=run.id,maskExposure=proof['exposedHeadPixels'],evaluation=evaluate(case_id,mode,provider,thresholds),status='passed')
        except Exception as error:
            row['status']='failed';row['errorType']=type(error).__name__;raise
        finally:progress()
    try:
        with httpx.Client(timeout=180,follow_redirects=False,trust_env=False) as client:
            if not rows:
                for case_id in plan['calibration']:
                    for mode in ('a','b','c'):
                        for reasoning in ('low','high'):call(client,case_id,mode,reasoning,'calibration')
            approval_path=FIX/'quality/calibration-review.json'
            if not approval_path.exists():
                raise Blocked('Review actual 12 outputs from local cache and create verification/fixtures/quality/calibration-review.json; resume with --resume '+run.id)
            approval=load(approval_path)
            require(approval.get('humanAttestation') is True and approval.get('reviewer') and approval.get('reviewedAt') and approval.get('sourceRun')==base_source,'calibration_review_not_bound_to_run')
            thresholds=thresholds_from_review(rows[:12],approval)
            best=approval.get('best',{})
            require(best.get('mode') in {'a','b','c'} and best.get('reasoning') in {'low','high'},'review_best_combination_missing')
            if len(rows)==12:
                # Repeat the frozen winning mode/reasoning on two held-out inputs
                # and one calibration input; never retune against held-out metrics.
                for case_id in [*plan['heldOut'],plan['calibration'][0]]:call(client,case_id,best['mode'],best['reasoning'],'best-repeat',thresholds)
                call(client,plan['calibration'][0],best['mode'],best['reasoning'],'top-only',thresholds)
            require(len(rows)==16,'poc_call_count_not_16')
            replay=[]
            for row in rows:
                provider=Path.home()/'.cache/street-fitting/poc'/row['localCacheRun']/(row['providerSha256']+'.png')
                require(provider.exists() and hashlib.sha256(provider.read_bytes()).hexdigest()==row['providerSha256'],'poc_provider_cache_missing_or_changed')
                if row['case'] in plan['heldOut']:
                    measured=evaluate(row['case'],row['maskMode'],provider.read_bytes(),thresholds)
                    require(measured==row['evaluation'],'heldout_native_decision_not_reproducible')
                    replay.append({'call':row['id'],'identical':True,'decision':measured.get('metrics',{}).get('decision','unsafe_output')})
            require(len(replay)==2,'heldout_replay_missing')
            run.save('thresholds.json',{'thresholds':thresholds,'sourceRun':base_source,'reviewer':approval['reviewer'],'method':'max accepted calibration boundary metrics, frozen before held-out calls','heldOut':replay})
            return {'providerCalls':16,'calls':rows,'thresholds':thresholds,'heldOut':replay,'productThresholdPromotion':'not automatic; owner must install this measured version and rerun native app gates'}
    finally:
        progress();remove_private(*set(staged))


def provenance(run,args):
    source=run_path(args.run)
    progress=load(source/'poc-progress.json')
    rows=progress.get('calls',[])
    require(rows and all(row.get('status')=='passed' for row in rows),'poc_provenance_requires_successful_recorded_calls')
    if not getattr(args,'app_run',None):
        raise Blocked('Separate PoC provenance needs --app-run <native-live-run> with actual download-OFF, provider-hash and MediaStore evidence')
    from backends import provenance as app_provenance
    from types import SimpleNamespace
    gate=app_provenance(None,SimpleNamespace(run=args.app_run))
    inspected=[]
    for row in rows:
        cache_id=row['localCacheRun']
        require(re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,127}',cache_id) and re.fullmatch(r'[a-f0-9]{64}',row['providerSha256']),'invalid_provider_cache_reference')
        file=Path.home()/'.cache/street-fitting/poc'/cache_id/(row['providerSha256']+'.png')
        if not file.is_file():raise Blocked('Original PoC provider bytes absent from local cache for '+row['id'])
        raw=file.read_bytes();require(hashlib.sha256(raw).hexdigest()==row['providerSha256'],'poc_provider_bytes_changed')
        with Image.open(io.BytesIO(raw)) as image:
            image.load()
            metadata=' '.join(value for value in image.info.values() if isinstance(value,str))
            gps=34853 in image.getexif() or bool(re.search(r'(?i)GPSLatitude|GPSLongitude|exif:GPS',metadata))
            inspected.append({'call':row['id'],'providerSha256':row['providerSha256'],'bytes':len(raw),'originalEncodingUnchanged':True,'metadataFields':len(image.info),'gpsPresent':gps})
    return {'sourceRun':args.run,'appGateRun':args.app_run,'providerFiles':inspected,'resultDownload':gate['resultDownload'],'galleryUnchangedInAppRun':gate['galleryUnchanged'],'watermarkPreservation':'unverified','metadataPreservation':'original encoded PoC bytes retained; no recompression','note':'Separate PoC has no export feature; referenced native app proves download OFF, not provider watermark semantics.'}
